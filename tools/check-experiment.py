#!/usr/bin/env python3
"""Check that every experiment folder carries the files its paste prompt promises.

Run from the repository root:

    python tools/check-experiment.py

Why this exists
---------------
The reproduce prompt tells a stranger's agent to "follow AGENTS.md" and to "start
with the free verification". If an experiment ships without `AGENTS.md` or
`verify.py`, that prompt points at nothing and the reader is stuck at step one,
with no way to tell whether the fault is theirs or ours.

That is not hypothetical. The publishing pipeline's template list contains
`experiment-README.md` and `METHODOLOGY.md` and no `AGENTS.md`, so an experiment
generated by it would ship exactly that way. This repository therefore checks its
own contract rather than trusting the thing that fills it.

Stdlib only, no dependencies, no network. Exits non-zero and names what is missing.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# A published experiment. Every one of these is referenced by the paste prompt,
# the runbook or the README, so a missing one is a broken promise, not untidiness.
EXPERIMENT_FILES = [
    "README.md",          # the write-up, and where the paste prompt lives
    "METHODOLOGY.md",     # how it was run
    "AGENTS.md",          # the runbook the prompt sends agents to
    "CLAUDE.md",          # points Claude Code at AGENTS.md
    "verify.py",          # Tier 1, the "free verification" the prompt promises
    ".env.example",       # so nobody is ever asked to paste a key into a chat
    "requirements.txt",
]
EXPERIMENT_DIRS = ["data", "results"]

# The skeleton. It has no data or results yet, by definition.
TEMPLATE_FILES = ["README.md", "AGENTS.md", "CLAUDE.md"]

problems: list[str] = []
checked = 0


def fail(where: Path, msg: str) -> None:
    problems.append(f"{where.relative_to(ROOT).as_posix()}: {msg}")


def check_claude_md(folder: Path) -> None:
    p = folder / "CLAUDE.md"
    if not p.exists():
        return
    body = p.read_text(encoding="utf-8").strip()
    if body != "@AGENTS.md":
        fail(p, f"should contain exactly '@AGENTS.md', found {body[:40]!r}")


def check_env_example(folder: Path) -> None:
    """Names, never values. A committed value is a leaked credential."""
    p = folder / ".env.example"
    if not p.exists():
        return
    for n, line in enumerate(p.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, _, value = line.partition("=")
        if value.strip():
            fail(p, f"line {n}: {name.strip()} has a value; "
                    f".env.example must carry names only")


def check_prompt_path(folder: Path, tag: str) -> None:
    """The paste prompt must point at where this experiment actually lives."""
    p = folder / "README.md"
    if not p.exists():
        return
    text = p.read_text(encoding="utf-8")
    m = re.search(r"git clone[^\n]*?&&\s*cd\s+([^\s`]+)", text)
    if not m:
        fail(p, "no reproduce prompt found (expected a 'git clone ... && cd ...' line)")
        return
    got = m.group(1).rstrip("`").strip()
    want = f"experiments/{tag}/{folder.name}"
    if got != want:
        fail(p, f"reproduce prompt points at {got!r}, but this experiment lives at {want!r}")


def check_experiment(folder: Path, tag: str) -> None:
    global checked
    checked += 1
    for f in EXPERIMENT_FILES:
        if not (folder / f).is_file():
            fail(folder, f"missing {f}")
    for d in EXPERIMENT_DIRS:
        if not (folder / d).is_dir():
            fail(folder, f"missing {d}/")
    check_claude_md(folder)
    check_env_example(folder)
    check_prompt_path(folder, tag)


def main() -> int:
    for tag in ("benchmarks", "tests"):
        base = ROOT / tag
        if not base.is_dir():
            continue
        for folder in sorted(p for p in base.iterdir() if p.is_dir()):
            check_experiment(folder, tag)

    tmpl = ROOT / "_template"
    if not tmpl.is_dir():
        problems.append("_template/: missing entirely")
    else:
        global checked
        checked += 1
        for f in TEMPLATE_FILES:
            if not (tmpl / f).is_file():
                fail(tmpl, f"missing {f}")
        check_claude_md(tmpl)

    print(f"checked {checked} folder(s) under benchmarks/, tests/ and _template/")
    if problems:
        print(f"\n{len(problems)} problem(s):")
        for p in problems:
            print(f"  {p}")
        print("\nEvery file above is referenced by a paste prompt, a runbook or a\n"
              "README. Shipping without one leaves a reader stuck with no way to\n"
              "tell whether the fault is theirs or ours.")
        return 1
    print("all experiments carry the files their paste prompt promises")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    raise SystemExit(main())
